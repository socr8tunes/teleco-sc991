def main(path):
    L = ["/* Generated by tools/gen_font.py - do not edit. */", ""]
    L.append("/* main font: 5 columns per glyph, bit 0 = top row; ASCII 32..126 */")
    L.append("static const uint8_t FONT_ASCII[95][5] = {")
    for i, g in enumerate(glyphs):
        L.append("    {%s},  /* %s */" % (", ".join("0x%02X" % b for b in g),
                 repr(chr(32 + i)).replace("*/", "* /")))
    L.append("};")
    L.append("")
    L.append("/* symbols 0x80.. (index = code - 0x80) */")
    L.append("#define FONT_SYM_COUNT %d" % (max(CUSTOM) - 0x80 + 1))
    L.append("static const uint8_t FONT_SYM[FONT_SYM_COUNT][5] = {")
    for code in range(0x80, max(CUSTOM) + 1):
        if code in CUSTOM:
            name, rows = CUSTOM[code]
            L.append("    {%s},  /* 0x%02X %s */" % (", ".join("0x%02X" % b for b in col_bytes(rows, 5)), code, name))
        else:
            L.append("    {0, 0, 0, 0, 0},  /* 0x%02X unused */" % code)
    L.append("};")
    L.append("")
    L.append("/* small font: 3 columns per glyph, bit 0 = top row (5 rows) */")
    L.append("typedef struct { unsigned char ch; unsigned char col[3]; } small_glyph_t;")
    L.append("static const small_glyph_t FONT_SMALL[] = {")
    for ch in sorted(SMALL):
        L.append("    {0x%02X, {%s}},  /* %s */" % (ord(ch), ", ".join("0x%02X" % b for b in col_bytes(SMALL[ch], 3)),
                 ch if ord(ch) < 127 and ord(ch) > 32 and ch != '*' else "."))
    L.append("};")
    L.append("#define FONT_SMALL_COUNT (sizeof FONT_SMALL / sizeof FONT_SMALL[0])")
    L.append("")
    open(path, "w").write("\n".join(L))

if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "core/renderer/font_data.inc")
