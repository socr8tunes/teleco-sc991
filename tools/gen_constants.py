#!/usr/bin/env python3
"""Generates core/units/constants_table.inc from scipy.constants (CODATA 2022 at the time of writing)."""
import sys
import scipy.constants as sc
from decimal import Decimal

P = sc.physical_constants
# (display name, symbol, scipy key or literal string, unit)
ROWS = [
    ("proton mass", "mp", "proton mass", "kg"),
    ("neutron mass", "mn", "neutron mass", "kg"),
    ("electron mass", "me", "electron mass", "kg"),
    ("muon mass", "mmu", "muon mass", "kg"),
    ("Bohr radius", "a0", "Bohr radius", "m"),
    ("Planck constant", "h", "Planck constant", "J s"),
    ("nuclear magneton", "muN", "nuclear magneton", "J/T"),
    ("Bohr magneton", "muB", "Bohr magneton", "J/T"),
    ("reduced Planck constant", "hbar", "reduced Planck constant", "J s"),
    ("fine-structure constant", "alpha", "fine-structure constant", ""),
    ("classical electron radius", "re", "classical electron radius", "m"),
    ("Compton wavelength", "lambda_c", "Compton wavelength", "m"),
    ("proton gyromagnetic ratio", "gamma_p", "proton gyromag. ratio", "1/(s T)"),
    ("proton Compton wavelength", "lambda_cp", "proton Compton wavelength", "m"),
    ("neutron Compton wavelength", "lambda_cn", "neutron Compton wavelength", "m"),
    ("Rydberg constant", "R_inf", "Rydberg constant", "1/m"),
    ("atomic mass constant", "u", "atomic mass constant", "kg"),
    ("proton magnetic moment", "mu_p", "proton mag. mom.", "J/T"),
    ("electron magnetic moment", "mu_e", "electron mag. mom.", "J/T"),
    ("neutron magnetic moment", "mu_n", "neutron mag. mom.", "J/T"),
    ("muon magnetic moment", "mu_mu", "muon mag. mom.", "J/T"),
    ("Faraday constant", "F", "Faraday constant", "C/mol"),
    ("elementary charge", "e", "elementary charge", "C"),
    ("Avogadro constant", "NA", "Avogadro constant", "1/mol"),
    ("Boltzmann constant", "k", "Boltzmann constant", "J/K"),
    ("molar volume of ideal gas", "Vm", "molar volume of ideal gas (273.15 K, 101.325 kPa)", "m3/mol"),
    ("molar gas constant", "R", "molar gas constant", "J/(mol K)"),
    ("speed of light in vacuum", "c0", "speed of light in vacuum", "m/s"),
    ("first radiation constant", "c1", "first radiation constant", "W m2"),
    ("second radiation constant", "c2", "second radiation constant", "m K"),
    ("Stefan-Boltzmann constant", "sigma", "Stefan-Boltzmann constant", "W/(m2 K4)"),
    ("electric constant", "eps0", "vacuum electric permittivity", "F/m"),
    ("magnetic constant", "mu0", "vacuum mag. permeability", "N/A2"),
    ("magnetic flux quantum", "phi0", "mag. flux quantum", "Wb"),
    ("standard gravity", "g", "standard acceleration of gravity", "m/s2"),
    ("conductance quantum", "G0", "conductance quantum", "S"),
    ("characteristic impedance of vacuum", "Z0", "characteristic impedance of vacuum", "ohm"),
    ("Celsius temperature zero", "t0", "273.15", "K"),
    ("Newtonian constant of gravitation", "G", "Newtonian constant of gravitation", "m3/(kg s2)"),
    ("standard atmosphere", "atm", "standard atmosphere", "Pa"),
]

out = ["/* Generated by tools/gen_constants.py from scipy.constants (%s). Do not edit. */" % sc.__name__]
for name, sym, key, unit in ROWS:
    if key == "273.15":
        v = "273.15"
    else:
        v = repr(P[key][0])
        v = format(Decimal(v), "E")
        # 17 significant digits come from repr; keep at most 12 (the precision of the experimental data)
        d = Decimal(repr(P[key][0]))
        v = "%.12g" % float(d)
        if key in ("speed of light in vacuum", "elementary charge", "Avogadro constant", "Boltzmann constant", "Planck constant", "standard acceleration of gravity", "standard atmosphere"):
            v = repr(P[key][0])        # exact by definition
    out.append('    {"%s", "%s", "%s", "%s"},' % (name, sym, v, unit))
open(sys.argv[1], "w").write("\n".join(out) + "\n")
print(len(ROWS), "constants")
