#!/usr/bin/env python3
"""Generate core/numeric/xconst.[ch]: high-precision constants as xnum literals.

Values come from mpmath (130 digits), never typed by hand. Re-run after any change:
    python3 tools/gen_xconst.py
"""
import os
import sys
from fractions import Fraction

import mpmath

mpmath.mp.dps = 150
B = 10**9
LIMBS = 6


def to_fraction(x):
    s = mpmath.nstr(x, 140, min_fixed=-10**9, max_fixed=10**9)
    from decimal import Decimal, getcontext
    getcontext().prec = 160
    d = Decimal(s)
    sign, digits, exp = d.as_tuple()
    n = int("".join(map(str, digits)))
    f = Fraction(n) * (Fraction(10) ** exp)
    return -f if sign else f


def xnum_literal(x):
    f = to_fraction(x)
    neg = f < 0
    f = abs(f)
    e = 0
    while f >= Fraction(B) ** e:
        e += 1
    while f < Fraction(B) ** (e - 1):
        e -= 1
    scaled = f / Fraction(B) ** e
    n = (scaled * B**LIMBS)
    n = int(n + Fraction(1, 2))          # round half up
    if n >= B**LIMBS:
        n = B**(LIMBS - 1)
        e += 1
    limbs = []
    for _ in range(LIMBS):
        n, r = divmod(n, B)
        limbs.append(r)
    limbs.reverse()
    return "{ { %su, %su, %su, %su, %su, %su }, %d, %d }" % (*limbs, e, 1 if neg else 0)


def main():
    mp = mpmath
    pi = mp.pi
    consts = [
        ("XC_PI", pi),
        ("XC_PIO2", pi / 2),
        ("XC_TWO_OVER_PI", 2 / pi),
        ("XC_LN2", mp.log(2)),
        ("XC_LN10", mp.log(10)),
        ("XC_INV_LN10", 1 / mp.log(10)),
        ("XC_E", mp.e),
        ("XC_SQRT2", mp.sqrt(2)),
        ("XC_DEG_PER_RAD", 180 / pi),
        ("XC_RAD_PER_DEG", pi / 180),
        ("XC_GRAD_PER_RAD", 200 / pi),
        ("XC_RAD_PER_GRAD", pi / 200),
    ]

    # pi/2 as base-1e9 chunks: chunk[0] = integer part (1), chunk[1..] = fractional groups
    f = to_fraction(pi / 2)
    ip = int(f)
    chunks = [ip]
    frac = f - ip
    NCH = 14
    for _ in range(NCH - 1):
        frac *= B
        c = int(frac)
        chunks.append(c)
        frac -= c

    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    hdr = ["/* GENERATED by tools/gen_xconst.py from mpmath. Do not edit. */",
           "#ifndef TELECO_NUMERIC_XCONST_H", "#define TELECO_NUMERIC_XCONST_H", "",
           '#include <stdint.h>', '#include "numeric/xnum.h"', ""]
    src = ["/* GENERATED by tools/gen_xconst.py from mpmath. Do not edit. */",
           '#include "numeric/xconst.h"', ""]
    for name, val in consts:
        hdr.append("extern const xnum_t %s;" % name)
        src.append("const xnum_t %s = %s;" % (name, xnum_literal(val)))
    hdr += ["", "#define XC_PIO2_CHUNKS %d" % NCH,
            "/* pi/2 in base 1e9: [0] = integer part, [1..] = successive 9-digit fractional groups */",
            "extern const uint32_t xc_pio2_chunks[XC_PIO2_CHUNKS];", "", "#endif", ""]
    src.append("")
    src.append("const uint32_t xc_pio2_chunks[XC_PIO2_CHUNKS] = {")
    for i in range(0, NCH, 4):
        src.append("    " + ", ".join("%du" % c for c in chunks[i:i + 4]) + ",")
    src.append("};")
    src.append("")
    with open(os.path.join(root, "core/numeric/xconst.h"), "w") as fh:
        fh.write("\n".join(hdr))
    with open(os.path.join(root, "core/numeric/xconst.c"), "w") as fh:
        fh.write("\n".join(src))
    print("wrote xconst.[ch]")


if __name__ == "__main__":
    sys.exit(main())
