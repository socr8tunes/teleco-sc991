#!/usr/bin/env python3
"""Generates tests/cases/capacity.txt and tests/ui/capacity.txt: boundary tests for the entry-capacity limits
(docs/exam/03-exam-specification-proposed.md section 3).  Expected values are computed independently in Python."""
import pathlib
ROOT = pathlib.Path(__file__).resolve().parents[2]
NEST, LIT, TOK = 24, 80, 256          # nested levels, number literals, entry-line tokens
S = ["# Generated by tests/tools/make_capacity_cases.py. Do not edit by hand.", ":reset", ":decimal"]
def nest(n, inner="1", o="(", c=")"): return o * n + inner + c * n
# brackets
S += [f"{nest(NEST)} => 1", f"{nest(NEST + 1)} => Stack ERROR", f"{nest(NEST-1, '2+3')}*2 => 10", f"{nest(NEST, '2+3')}*2 => 10", f"{nest(NEST + 1, '2+3')}*2 => Stack ERROR"]
# function calls (each is a nesting level)
S += [f"{nest(NEST, '0', 'sin(', ')')} => 0", f"{nest(NEST + 1, '0', 'sin(', ')')} => Stack ERROR", f"{nest(NEST, '4', 'abs(', ')')} => 4"]
# mixed levels: alternating bracket / function
mix = lambda n: "".join("(" if i % 2 else "abs(" for i in range(n)) + "5" + ")" * n
S += [f"{mix(NEST)} => 5", f"{mix(NEST + 1)} => Stack ERROR"]
# unary minus does not consume nesting levels but chains of them stay valid: (-(-(...)))
neg = lambda n: "-(" * n + "1" + ")" * n
S += [f"{neg(NEST)} => 1", f"{neg(NEST + 1)} => Stack ERROR"]
# natural-display structures typed as text are fractions via frac{}{}? skip: covered by UI tests below
# literals
def total(n, f): return sum(f(i) for i in range(1, n + 1))
ones = lambda n: "+".join(["1"] * n)
S += [f"{ones(LIT)} => {LIT}", f"{ones(LIT + 1)} => Stack ERROR", f"{ones(LIT - 1)} => {LIT - 1}"]
twos = lambda n: "+".join(str(10 + i) for i in range(n))
S += [f"{twos(LIT)} => {sum(10 + i for i in range(LIT))}", f"{twos(LIT + 1)} => Stack ERROR"]
dec = lambda n: "+".join(".5" for _ in range(n))
S += [f"{dec(LIT)} => {LIT // 2}", f"{dec(LIT + 1)} => Stack ERROR"]
# literals inside functions, arguments counted as literals too
mixed = lambda n: "+".join("abs(1)" if i % 2 else "1" for i in range(n))
S += [f"{mixed(LIT)} => {LIT}", f"{mixed(LIT + 1)} => Stack ERROR"]
# the line-length limit binds first for 3-token literals such as 0.5: 80 of them need 319 tokens (> 288 compile buffer)
S += [f"{'+'.join(['0.5'] * LIT)} => Stack ERROR"]
# 24 nested levels and 80 literals together
both = "(" * NEST + "+".join(["1"] * LIT) + ")" * NEST
S += [f"{both} => {LIT}"]
# value stack: 24 pending operands plus a 4-unknown system (20 arguments) at the innermost level
S += ["1+(" * 0 + "simul4(1,0,0,0,1,0,1,0,0,2,0,0,1,0,3,0,0,0,1,4) => 1 | y = 2 | z = 3 | w = 4"]
S += [("2*(" * 20) + "3" + ")" * 20 + " => " + str(3 * 2 ** 20)]
S += ["# interval / body functions nested inside one another (limit 24 body levels is far above what 80 literals allow)",
      "sum(sum(sum(1,1,2),1,2),1,2) => 8", "prod(prod(2,1,2),1,2) => 16"]
(ROOT / "tests/cases/capacity.txt").write_text("\n".join(S) + "\n")

U = ["# Generated by tests/tools/make_capacity_cases.py. Key-sequence boundary tests for entry capacity."]
k = lambda s: " ".join(s)
U += [f"{k('(' * NEST)} 1 {k(')' * NEST)} EXE => 1", f"{k('(' * (NEST + 1))} 1 {k(')' * (NEST + 1))} EXE => Stack ERROR"]
# entry line capacity: 256 tokens accepted, the 257th key press is ignored
fill = "1 + " * 127 + "1 +"            # 256 tokens
U += [f"{fill} => expr:{'1+' * 128}"]
U += [f"{fill} 1 => expr:{'1+' * 128}", f"{fill} 1 1 1 => expr:{'1+' * 128}"]       # extra presses ignored
U += [f"{fill} 1 DEL 1 => expr:{'1+' * 127}11"]                                         # room is freed again by DEL
# 80 literals typed with keys
lits = " + ".join(["1"] * 80)
U += [f"{lits} EXE => 80", f"{lits} + 1 EXE => Stack ERROR"]
(ROOT / "tests/ui/capacity.txt").write_text("\n".join(U) + "\n")
print("wrote capacity cases:", len(S), "script lines,", len(U), "ui lines")
