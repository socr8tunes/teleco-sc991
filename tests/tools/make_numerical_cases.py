#!/usr/bin/env python3
"""Generates tests/cases/numerical_{integrals,derivatives,solve}.txt - independent-oracle, boundary, error and
regression cases for the numerical methods (P1). Expected values come from mpmath at 50 digits, never from the
calculator. `~>` compares numerically with relative tolerance 1E-8; `=>` compares text.

Integral classes (decision D4: conservative non-convergence):
  CONVERGES   integrable, the calculator must return the value (within 1E-8)
  DIVERGES    divergent or undefined: Math ERROR
  UNVERIFIED  mathematically convergent but too oscillatory / singular / wide-ranging for the 80-interval Gauss-Kronrod
              scheme to verify: Math ERROR is the documented outcome (never a plausible wrong number)
Run:  python3 tests/tools/make_numerical_cases.py"""
import pathlib
import mpmath as mp
mp.mp.dps = 50
ROOT = pathlib.Path(__file__).resolve().parents[2]
X = mp.mpf

def num(v):
    v = mp.mpf(v)
    return mp.nstr(v, 15).replace("e+", "E").replace("e-", "E-")

def lit(t):
    return str(t).replace("e+", "E").replace("e-", "E-")

class File:
    def __init__(self, name, head):
        self.name, self.l = name, ["# " + head, ":decimal", ":rad"]
    def eq(self, expr, val, note=None):
        if note: self.l.append(f"# {note}")
        self.l.append(f"{expr} ~> {num(val)}")
    def txt(self, expr, res, note=None):
        if note: self.l.append(f"# {note}")
        self.l.append(f"{expr} => {res}")
    def save(self):
        (ROOT / "tests/cases" / self.name).write_text("\n".join(self.l) + "\n")
        print(self.name, sum(1 for x in self.l if "~>" in x or " => " in x), "cases")

# ------------------------------------------------------------------ integrals
I = File("numerical_integrals.txt", "Generated by tests/tools/make_numerical_cases.py (mpmath). Do not edit by hand.")
CONV = [("X^2", lambda x: x**2, "0", "1", None), ("sin(X)", mp.sin, "0", "pi", None), ("e^X", mp.exp, "0", "1", None), ("1/X", lambda x: 1/x, "1", "100", None),
 ("e^(-X^2)", lambda x: mp.exp(-x*x), "-10", "10", [-10, 0, 10]), ("e^(-X^2)", lambda x: mp.exp(-x*x), "-1000", "1000", [-1000, -10, 0, 10, 1000]),
 ("1/(1+X^2)", lambda x: 1/(1+x*x), "-1E6", "1E6", [-10**6, -1000, 0, 1000, 10**6]), ("sqrt(1-X^2)", lambda x: mp.sqrt(1-x*x), "-1", "1", None),
 ("ln(X)", mp.log, "0", "1", None), ("1/sqrt(X)", lambda x: 1/mp.sqrt(x), "0", "1", None), ("abs(X-0.3)", lambda x: abs(x-X("0.3")), "0", "1", [0, X("0.3"), 1]),
 ("e^(-X)", lambda x: mp.exp(-x), "0", "50", None), ("X^-0.5", lambda x: x**X("-0.5"), "0", "4", None), ("sin(1/X)", lambda x: mp.sin(1/x), "0.1", "1", None),
 ("X*sin(X)", lambda x: x*mp.sin(x), "0", "10", None), ("e^(-X)*sin(X)", lambda x: mp.exp(-x)*mp.sin(x), "0", "20", None), ("sqrt(X)", mp.sqrt, "0", "4", None),
 ("1/(X^2+1)", lambda x: 1/(x*x+1), "0", "1", None), ("X^3-2X", lambda x: x**3-2*x, "-2", "3", None), ("tan(X)", mp.tan, "0", "1", None),
 ("ln(X)^2", lambda x: mp.log(x)**2, "0", "1", None), ("sin(X)/X", lambda x: mp.sin(x)/x, "0.001", "10", None), ("e^(-(X-50)^2)", lambda x: mp.exp(-(x-50)**2), "0", "100", [0, 40, 50, 60, 100]),
 ("sqrt(X)*ln(X)", lambda x: mp.sqrt(x)*mp.log(x), "0", "1", None), ("e^X", mp.exp, "-100", "5", None), ("X^10", lambda x: x**10, "-3", "3", None),
 ("abs(sin(X))", lambda x: abs(mp.sin(x)), "0", "10", [mp.pi*k for k in range(4)] + [10]), ("cos(X^2)", lambda x: mp.cos(x*x), "0", "5", None),
 ("X^2", lambda x: x**2, "1", "0", None), ("X", lambda x: x, "2", "2", None), ("1E-5*X", lambda x: 1e-5*x, "0", "1E5", None)]
I.l.append("# CONVERGES: integrable, value required (within 1E-8)")
for t, f, a, b, pts in CONV:
    A, B = mp.mpmathify(a.replace("pi", "pi") if a != "pi" else mp.pi) if False else None, None
    av = mp.pi if a == "pi" else X(a.replace("E", "e")); bv = mp.pi if b == "pi" else X(b.replace("E", "e"))
    p = pts or [av, bv]
    I.eq(f"integral({t},{a},{b})", mp.quad(f, p) if av != bv else 0)
I.l.append("# DIVERGES: divergent, undefined or non-integrable: Math ERROR, never a number")
for t, a, b in (("1/X", "-1", "1"), ("1/X", "0", "1"), ("1/X", "-1", "2"), ("1/X^2", "-1", "1"), ("1/X^2", "0", "1"), ("X^-1.1", "0", "1"), ("tan(X)", "0", "2"), ("tan(X)", "0", "1.6"),
                ("1/(X-1)", "0", "2"), ("1/(X-0.5)", "0", "1"), ("1/(X-0.3)", "0", "1"), ("1/abs(X)", "-1", "1"), ("ln(X)", "-1", "1"), ("sqrt(X)", "-1", "1"), ("1/X", "0.001", "1E99"),
                ("X", "0", "1E99"), ("e^X", "0", "300"), ("1/(1-X)", "0", "1"), ("1/sin(X)", "0", "1"), ("1/(X^2-1)", "0", "2"), ("X^-2", "-1", "1"), ("1/(X-0.7)^2", "0", "1"),
                ("1/(X-2)", "1", "3.5"), ("tan(X)", "0", "3"), ("1/X^3", "-1", "2"), ("e^X", "0", "1000"), ("1/X", "-3", "3")):
    I.txt(f"integral({t},{a},{b})", "Math ERROR")
I.l.append("# UNVERIFIED: convergent but beyond the scheme (documented limitation D4): Math ERROR, never a wrong number")
for t, a, b, why in (("X^-0.9", "0", "1", "strong endpoint singularity (true value 10)"), ("1/X^2", "1", "1E50", "range spans 50 decades"), ("1/sqrt(1-X^2)", "-1", "1", "two inverse-sqrt endpoints, slow convergence"),
                     ("1/X", "1", "1E50", "range spans 50 decades"), ("cos(X)", "0", "1000", "160 oscillations"), ("sin(100X)", "0", "10", "318 oscillations"), ("sin(1/X)", "0.001", "1", "oscillation accumulating at 0.001")):
    I.txt(f"integral({t},{a},{b})", "Math ERROR", why)
I.l.append("# D15 narrow peaks: the range is seeded with 8 panels; a peak that is resolved is integrated correctly, and one that falls between all samples (every sample exactly 0) is Math ERROR, never 0")
for k, c in ((100, "0.3"), (1000, "0.013"), (1E5, "0.37"), (1E6, "0.5"), (1E8, "0.3")):
    kk, cc = X(k), X(c)
    s = mp.sqrt(kk)
    I.eq(f"integral(e^(-{lit(num(kk))}(X-{c})^2),0,1)", mp.sqrt(mp.pi) / (2 * s) * (mp.erf(s * (1 - cc)) + mp.erf(s * cc)))
for e in ("integral(e^(-1E8(X-0.749795)^2),0,1)", "integral(e^(-1E14(X-0.5)^2),0,1)"):
    I.txt(e, "Math ERROR", "partly resolved narrow peak: the 8-panel and 11-panel runs disagree (a single run returned 1.7691E-4 instead of 1.7725E-4); no number is shown")
for e in ("integral(e^X,-1E5,0)", "integral(e^(-X),0,1E5)"):
    I.eq(e, 1, "endpoint peak, formerly returned 0 (known defect), now resolved by the seed panels")
for e, why in (("integral(e^(-(X-0.3)^2*1E16),0,1)", "peak width 1E-8 between all samples"), ("integral(e^(-X*1E6),0,1000)", "peak at the endpoint 1E-6 wide in a range of 1000"),
               ("integral(e^(-X),0,1E10)", "peak at the endpoint, range 1E10"), ("integral(0,0,1)", "identically zero integrand cannot be told from a missed peak (documented)")):
    I.txt(e, "Math ERROR", why)
I.save()

# ------------------------------------------------------------------ derivatives
D = File("numerical_derivatives.txt", "Generated by tests/tools/make_numerical_cases.py (mpmath diff). Do not edit by hand.")
D.l.append("# values: relative step, tiny and huge arguments")
for t, f, x0 in (("X^2", lambda x: x**2, "3"), ("X^3", lambda x: x**3, "2"), ("e^X", mp.exp, "1"), ("ln(X)", mp.log, "2"), ("sin(X)", mp.sin, "1"), ("cos(X)", mp.cos, "0.5"), ("1/X", lambda x: 1/x, "2"),
                 ("tan(X)", mp.tan, "1"), ("sqrt(X)", mp.sqrt, "4"), ("X^5", lambda x: x**5, "1E10"), ("e^X", mp.exp, "-20"), ("atan(X)", mp.atan, "100"),
                 ("X^2", lambda x: x**2, "1E-10"), ("X^2", lambda x: x**2, "-1E-10"), ("X^2", lambda x: x**2, "1E-40"), ("X^3", lambda x: x**3, "1E-30"), ("X^5", lambda x: x**5, "1E-15"),
                 ("X^2", lambda x: x**2, "0.001"), ("e^X", mp.exp, "1E-10"), ("ln(1+X)", lambda x: mp.log(1+x), "1E-12"), ("X^2", lambda x: x**2, "1E20"), ("sqrt(X)", mp.sqrt, "1E-20"),
                 ("X^3", lambda x: x**3, "-1E-30"), ("1/X", lambda x: 1/x, "1E-20"), ("X^4", lambda x: x**4, "1E-20")):
    D.eq(f"ddx({t},{x0})", mp.diff(f, X(x0.replace("E", "e"))))
D.l.append("# exact zeros and kinks")
D.txt("ddx(5,3)", "0"); D.txt("ddx(X^3,0)", "0"); D.txt("ddx(abs(X),1)", "1"); D.txt("ddx(abs(X),-1)", "-1"); D.txt("ddx(abs(X),0)", "0")
D.l.append("# errors: function undefined or overflowing near the point")
for e in ("ddx(sqrt(X),0)", "ddx(ln(X),-1)", "ddx(ln(X),0)", "ddx(X^3,1E50)", "ddx(1/X,0)"): D.txt(e, "Math ERROR")
D.save()

# ------------------------------------------------------------------ solve
S = File("numerical_solve.txt", "Generated by tests/tools/make_numerical_cases.py (mpmath roots). Do not edit by hand.")
S.l.append("# roots at ordinary and extreme scales (relative tolerance)")
for txt, rhs, g, root in (("X^2", "2", "1", mp.sqrt(2)), ("X^2", "2", "-1", -mp.sqrt(2)), ("e^X", "5", "1", mp.log(5)), ("cos(X)", "X", "1", mp.findroot(lambda x: mp.cos(x) - x, 0.7)),
        ("X^3-2X", "5", "2", mp.findroot(lambda x: x**3 - 2*x - 5, 2)), ("ln(X)", "0", "2", X(1)), ("X^2", "4", "0.5", X(2)), ("1/X", "4", "1", X("0.25")),
        ("X^2", "1E20", "1", X(10)**10), ("X^2", "1E-20", "1", X(10)**-10), ("X^2", "1E-40", "1", X(10)**-20), ("X^3", "1E-30", "1", X(10)**-10), ("1E-30*X", "1E-40", "1", X(10)**-10),
        ("sin(X)", "0.5", "0.4", mp.asin(X("0.5"))), ("e^X", "1E-90", "1", mp.log(X(10)**-90)), ("X^2", "1E-60", "1", X(10)**-30), ("X^3", "1E60", "1", X(10)**20),
        ("1E30*X", "1E40", "1", X(10)**10), ("X^2-4X", "-4", "5", X(2)), ("(X-1)^2", "0", "3", X(1)), ("(X-1)^3", "0", "3", X(1)), ("X^2", "0", "1", X(0)), ("X^2", "0", "0.001", X(0))):
    S.eq(f"solve({txt}={rhs},{g})", root)
S.l.append("# no real root, plateaus and underflow: Can't Solve (previously a bogus root)")
for e in ("solve(X^2=-1,1)", "solve(X=X+1,0)", "solve(sin(X)=2,1)", "solve(abs(X)=-1,1)", "solve(e^X=0,1)", "solve(e^X=0,-300)", "solve(X^2+1E-30=0,1)", "solve(X=X+1E-20,1)",
          "solve(1/X=0,1)", "solve(10^X=0,0)", "solve(e^(-X^2)=0,1)", "solve(X^2+1E-60=0,0.5)"):
    S.txt(e, "Can't Solve")
S.save()
