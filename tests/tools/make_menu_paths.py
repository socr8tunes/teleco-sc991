#!/usr/bin/env python3
"""Generates tests/ui/menu_paths.txt: every function reachable from MENU is entered through its menu path
(MENU, DOWN x j, EXE, DOWN x i, EXE), given arguments with plain keys, and the displayed result must equal the result of
the same expression typed as text (evaluated by build/test_script). Menu positions come from the live menu tables
(build/test_exclusions --paths), so a reordered menu regenerates the file instead of silently breaking it.
Run after building:  python3 tests/tools/make_menu_paths.py"""
import subprocess, pathlib, re, tempfile
ROOT = pathlib.Path(__file__).resolve().parents[2]
B = ROOT / "build"
out = subprocess.run([str(B / "test_exclusions"), str(ROOT / "tests/exam/approved_tokens.txt"), "--paths"], capture_output=True, text=True).stdout
paths = {}
for l in out.splitlines():
    m = re.match(r"PATH (\d+) (\d+) (.*)$", l)
    if m: paths[(int(m[1]), int(m[2]))] = m[3]
# (menu label) -> list of (argument keys, expression text)
ARGS = {
 "sinh(": [("1 )", "sinh(1)"), ("0 )", "sinh(0)")], "cosh(": [("1 )", "cosh(1)")], "tanh(": [("1 )", "tanh(1)")],
 "sinh{-1}(": [("1 )", "asinh(1)")], "cosh{-1}(": [("2 )", "acosh(2)"), ("0 )", "acosh(0)")], "tanh{-1}(": [("0 . 5 )", "atanh(0.5)"), ("1 )", "atanh(1)")],
 "Abs(": [("NEG 5 )", "abs(-5)")], "Int(": [("NEG 2 . 5 )", "int(-2.5)")], "Intg(": [("NEG 2 . 5 )", "intg(-2.5)")], "Rnd(": [("2 / 3 )", "rnd(2/3)")],
 "log{b}(": [("2 , 8 )", "log(2,8)"), ("1 , 8 )", "log(1,8)")], "Pol(": [("3 , 4 )", "pol(3,4)")], "Rec(": [("5 , 0 )", "rec(5,0)")],
 "GCD(": [("1 2 , 1 8 )", "gcd(12,18)")], "LCM(": [("4 , 6 )", "lcm(4,6)")], "Quot(": [("1 7 , 5 )", "quot(17,5)")], "Rem(": [("1 7 , 5 )", "rem(17,5)")],
 "PFact(": [("1 2 )", "pfact(12)")],
 "NormP(": [("1 )", "normp(1)")], "NormQ(": [("1 )", "normq(1)")], "NormR(": [("1 )", "normr(1)")], "InvN(": [("0 . 5 )", "invn(0.5)")],
 "BinomPD(": [("1 0 , 0 . 5 , 3 )", "binompd(10,0.5,3)")], "BinomCD(": [("1 0 , 0 . 5 , 3 )", "binomcd(10,0.5,3)")],
 "PoisPD(": [("2 , 1 )", "poispd(2,1)")], "PoisCD(": [("2 , 1 )", "poiscd(2,1)")],
}
POST = {"P": ("5 P 2", "5nPr2"), "C": ("5 C 2", "5nCr2"), "!": ("5 !", "5!")}
BYPOS = {(1, 0): ("ALPHA ) SQ , 1 , 4 )", "sum(X^2,1,4)"), (1, 6): ("ALPHA ) , 1 , 5 )", "prod(X,1,5)"),
         (1, 1): ("ALPHA ) SQ , 3 )", "ddx(X^2,3)"), (1, 2): ("ALPHA ) SQ , 0 , 3 )", "integral(X^2,0,3)")}
for (j, i), (k, e) in BYPOS.items(): ARGS[paths[(j, i)] + "#%d%d" % (j, i)] = [(k, e)]
paths = {key: (lab + "#%d%d" % key if key in BYPOS else lab) for key, lab in paths.items()}
lines = ["# generated by tests/tools/make_menu_paths.py - menu key paths; do not edit by hand"]
cases = []
for (j, i), lab in sorted(paths.items()):
    if lab in ARGS:
        for k, e in ARGS[lab]: cases.append((j, i, lab, k, e))
for j, i, lab, k, e in cases:
    cases_txt = None
with tempfile.NamedTemporaryFile("w", suffix=".txt", delete=False) as f:
    f.write(":reset\n"); [f.write(f"{e} => x\n") for *_, e in cases]
res = subprocess.run([str(B / "test_script"), f.name], capture_output=True, text=True).stdout
got = re.findall(r"got:\s+(.*)", res)
assert len(got) == len(cases), (len(got), len(cases), res[:400])
for (j, i, lab, k, e), g in zip(cases, got):
    keys = "MENU " + "DOWN " * j + "EXE " + "DOWN " * i + "EXE " + k.replace(",", "SHIFT )") + " EXE"      # SHIFT ) is the comma key
    lines.append(f"# {lab}  ({e})"); lines.append(f"{keys} => {g}")
# operator-style menu items (infix / postfix)
for (j, i), lab in sorted(paths.items()):
    if lab in ("P", "C", "!") and (j, i) in paths:
        pre = {"P": "5", "C": "5", "!": "5"}[lab]
        post = {"P": " 2", "C": " 2", "!": ""}[lab]
        e = {"P": "5nPr2", "C": "5nCr2", "!": "5!"}[lab]
        r = subprocess.run([str(B / "test_script"), "/dev/stdin"], input=f":reset\n{e} => x\n", capture_output=True, text=True).stdout
        g = re.findall(r"got:\s+(.*)", r)[0]
        lines.append(f"# {lab} ({e})"); lines.append(f"{pre} MENU " + "DOWN " * j + "EXE " + "DOWN " * i + f"EXE{post} EXE => {g}")
(ROOT / "tests/ui/menu_paths.txt").write_text("\n".join(lines) + "\n")
print(len(lines) // 2, "menu path cases")
