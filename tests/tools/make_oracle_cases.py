#!/usr/bin/env python3
"""Generates tests/cases/oracle_*.txt: matrix, vector, complex, base-n, function-domain and statistics-error cases.

Expected values come from independent oracles, never from the calculator:
  matrices / vectors   exact Python Fractions (Bareiss determinant, Gauss-Jordan inverse)
  complex, functions   mpmath at 60 digits, rounded once to the calculator's 10-digit display
  base-n               Python integers with explicit 32-bit two's-complement wrap/overflow rules
  errors               the mathematical definition (singular matrix, domain, overflow); each case states why.
Cases whose 10-digit rounding is unstable under a +-1e-13 relative perturbation are skipped, so a correct
16-digit calculator can never disagree with the oracle because of a near-tie.  Seeded: output is reproducible."""
import pathlib, random
from fractions import Fraction
from decimal import Decimal, ROUND_HALF_UP
import mpmath as mp

mp.mp.dps = 60
ROOT = pathlib.Path(__file__).resolve().parents[2]
R = random.Random(9910)

def disp(fr):
    fr = Fraction(fr)
    if fr == 0: return "0"
    d = Decimal(fr.numerator) / Decimal(fr.denominator)
    ex = d.adjusted()
    q = d.scaleb(-ex).quantize(Decimal("1.000000000"), rounding=ROUND_HALF_UP)
    if abs(q) >= 10: q = q / 10; ex += 1
    digits = format(q.normalize(), "f")
    if ex < -2 or ex > 9: return digits + "E" + str(ex)
    return format(Decimal(digits).scaleb(ex).normalize(), "f")

def fr_of(x):
    return Fraction(mp.nstr(x, 55, min_fixed=-1000, max_fixed=1000)) if x != 0 else Fraction(0)

def stable(fr):
    fr = Fraction(fr)
    if fr == 0: return True
    e = Fraction(1, 10**13)
    return disp(fr * (1 + e)) == disp(fr) == disp(fr * (1 - e))

class Out:
    def __init__(self, header, pre=()):
        self.l = ["# " + header, ":reset", ":decimal", *pre]; self.n = 0
    def add(self, expr, expect, why=None):
        if why: self.l.append("# " + why)
        self.l.append(f"{expr} => {expect}"); self.n += 1
    def write(self, name):
        (ROOT / "tests/cases" / name).write_text("\n".join(self.l) + "\n"); print(f"{name}: {self.n} cases")

# ------------------------------------------------------------------ matrices
def mtext(m): return "[" + ";".join(",".join(str(x) for x in row) for row in m) + "]"
def mres(m): return "[" + ", ".join("[" + ", ".join(disp(x) for x in row) + "]" for row in m) + "]"
def mdet(m):
    a = [[Fraction(x) for x in r] for r in m]; n = len(a); d = Fraction(1)
    for i in range(n):
        p = next((r for r in range(i, n) if a[r][i] != 0), None)
        if p is None: return Fraction(0)
        if p != i: a[i], a[p] = a[p], a[i]; d = -d
        d *= a[i][i]
        for r in range(i + 1, n):
            f = a[r][i] / a[i][i]
            a[r] = [x - f * y for x, y in zip(a[r], a[i])]
    return d
def minv(m):
    n = len(m); a = [[Fraction(x) for x in r] + [Fraction(int(i == j)) for j in range(n)] for i, r in enumerate(m)]
    for i in range(n):
        p = next(r for r in range(i, n) if a[r][i] != 0)
        a[i], a[p] = a[p], a[i]
        pv = a[i][i]; a[i] = [x / pv for x in a[i]]
        for r in range(n):
            if r != i:
                f = a[r][i]; a[r] = [x - f * y for x, y in zip(a[r], a[i])]
    return [r[n:] for r in a]
def mmul(a, b): return [[sum(Fraction(a[i][k]) * b[k][j] for k in range(len(b))) for j in range(len(b[0]))] for i in range(len(a))]
def rnd(r, c, lo=-9, hi=9): return [[R.randint(lo, hi) for _ in range(c)] for _ in range(r)]

