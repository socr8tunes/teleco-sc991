# ------------------------------------------------------------------ base-n
LO, HI = -2**31, 2**31 - 1
def wrap(x): return x
def bfmt(x, base):
    if base == 10: return str(x)
    u = x & 0xFFFFFFFF
    return {16: format(u, "X"), 8: format(u, "o"), 2: format(u, "b")}[base]
def btok(x, base):          # how a 32-bit pattern is typed in a given base
    u = x & 0xFFFFFFFF
    if base == 10: return str(x) if x >= 0 else f"({x})"
    return bfmt(u, base)
def tdiv(a, b): q = abs(a) // abs(b); return q if (a >= 0) == (b >= 0) else -q
B = {}
edge = [0, 1, -1, 2, 5, 10, 255, 256, 65535, 65536, 2**30, HI, LO, HI - 1, LO + 1, 0x55555555, -0x55555556, 12345678, -12345678]
for name, base, pre in (("hex", 16, ":hex"), ("bin", 2, ":bin"), ("oct", 8, ":oct"), ("dec", 10, ":dec")):
    O = Out(f"Generated by tests/tools/make_oracle_cases.py (Python integers, 32-bit two's complement). {name} mode. Do not edit by hand.", (pre,))
    ops = [("+", lambda a, b: a + b), ("-", lambda a, b: a - b), ("*", lambda a, b: a * b),
           ("and", lambda a, b: a & b), ("or", lambda a, b: a | b), ("xor", lambda a, b: a ^ b), ("xnor", lambda a, b: ~(a ^ b))]
    pairs = [(R.choice(edge), R.choice(edge)) for _ in range(60 if base != 2 else 40)]
    if base == 2: pairs = [(a, b) for a, b in pairs if abs(a) < 2**20 and abs(b) < 2**20 or R.random() < .3]
    for a, b in pairs:
        for sym, f in ops:
            r = f(a, b)
            if sym in ("and", "or", "xor", "xnor"):
                r = ((r + 2**31) % 2**32) - 2**31
            expect = "Math ERROR" if not (LO <= r <= HI) else bfmt(r, base)
            if base == 10 and not (LO <= r <= HI): expect = "Math ERROR"
            O.add(f"{btok(a, base)}{sym if sym in '+-*' else ' ' + sym + ' '}{btok(b, base)}", expect,
                  "overflow of the signed 32-bit range" if expect == "Math ERROR" else None)
    for a, b in [(100, 7), (7, 100), (1000, 3), (255, 16), (HI, 2), (-100, 7), (100, -7), (-100, -7), (0, 5)]:
        O.add(f"{btok(a, base)}/{btok(b, base)}", bfmt(tdiv(a, b), base), "integer division truncates toward zero")
    O.add(f"{btok(5, base)}/{btok(0, base)}", "Math ERROR", "division by zero")
    for a in edge:
        O.add(f"not({btok(a, base)})", bfmt(~a, base)); n = -a
        O.add(f"neg({btok(a, base)})", "Math ERROR" if not (LO <= n <= HI) else bfmt(n, base), "-(-2^31) overflows" if not (LO <= n <= HI) else None)
    for a in edge[:8]:
        O.add(f"{btok(a, base)}", bfmt(a, base))
    if base == 16:
        for bad in ("G", "1G", "1.5", "FFFFFFFF1", "100000000", "FFFFFFFF+100000000"):
            O.add(bad, "Syntax ERROR" if bad in ("G", "1G", "1.5") else "Math ERROR", "invalid digit or more than 32 bits")
    if base == 2:
        O.add("2", "Syntax ERROR", "digit 2 invalid in binary"); O.add("102", "Syntax ERROR")
        O.add("1" * 33, "Math ERROR", "33 bits"); O.add("1" * 32, "11111111111111111111111111111111")
    if base == 8:
        O.add("8", "Syntax ERROR", "digit 8 invalid in octal"); O.add("37777777777", "37777777777"); O.add("40000000000", "Math ERROR", "more than 32 bits")
    if base == 10:
        O.add("2147483647", "2147483647"); O.add("2147483648", "Math ERROR", "above the 32-bit signed range")
        O.add("2147483647+1", "Math ERROR"); O.add("(-2147483647)-1", "-2147483648"); O.add("(-2147483647)-2", "Math ERROR")
    O.write(f"oracle_basen_{name}.txt")

