# ------------------------------------------------------------------ complex
def cstr(z):
    re, im = fr_of(z.real), fr_of(z.imag)
    if not (stable(re) and stable(im)): return None
    if im == 0: return disp(re)
    ims = "" if abs(im) == 1 else disp(abs(im))
    if re == 0: return ("-" if im < 0 else "") + ims + "i"
    return disp(re) + ("-" if im < 0 else "+") + ims + "i"
def ctext(a, b): return f"({a}{'+' if b >= 0 else '-'}{abs(b)}i)"
C = Out("Generated by tests/tools/make_oracle_cases.py (mpmath, 60 digits). Complex-number tests. Do not edit by hand.", (":cmplx on",))
for _ in range(14):
    a, b, c, d = (R.randint(-9, 9) for _ in range(4))
    if c == 0 and d == 0: continue
    z, w = mp.mpc(a, b), mp.mpc(c, d)
    for op, res in (("+", z + w), ("-", z - w), ("*", z * w), ("/", z / w)):
        s = cstr(res)
        if s: C.add(f"{ctext(a, b)}{op}{ctext(c, d)}", s)
    for e in (2, 3):
        s = cstr(z ** e)
        if s: C.add(f"{ctext(a, b)}^{e}", s)
    s = cstr(mp.sqrt(z))
    if s and (a or b): C.add(f"sqrt({ctext(a, b)})", s)
    if a or b:
        s = cstr(mp.mpc(abs(z))); 
        if s: C.add(f"abs({ctext(a, b)})", s)
        s = cstr(mp.mpc(mp.degrees(mp.arg(z))))
        if s: C.add(f"arg({ctext(a, b)})", s)
        s = cstr(mp.log(z))
        if s: C.add(f"ln({ctext(a, b)})", s)
