#!/usr/bin/env python3
"""Generates tests/cases/product.txt for the product operator. Expected values are computed
independently with Python integers/Fractions (exact), then formatted like the calculator's 10-digit display."""
import math, sys
from fractions import Fraction
from decimal import Decimal, ROUND_HALF_UP

def disp(fr):
    fr = Fraction(fr)
    if fr == 0: return "0"
    d = Decimal(fr.numerator) / Decimal(fr.denominator)
    ex = d.adjusted()
    q = d.scaleb(-ex).quantize(Decimal("1.000000000"), rounding=ROUND_HALF_UP)
    if abs(q) >= 10: q = q / 10; ex += 1
    digits = format(q.normalize(), "f")
    if ex < -2 or ex > 9: return digits + "E" + str(ex)
    return format(Decimal(digits).scaleb(ex).normalize(), "f")

def P(f, a, b):
    r = Fraction(1)
    for x in range(a, b + 1): r *= f(Fraction(x))
    return r

L = ["# Generated by tests/tools/make_product_cases.py (exact Python Fractions). Do not edit by hand.", ":reset", ":decimal"]
cases = [("prod(X,1,5)", lambda x: x, 1, 5), ("prod(X,1,20)", lambda x: x, 1, 20), ("prod(X,1,10)", lambda x: x, 1, 10),
 ("prod(X,1,0)", lambda x: x, 1, 0), ("prod(2,1,10)", lambda x: 2 + 0 * x, 1, 10), ("prod(1+1/X,1,9)", lambda x: 1 + 1 / x, 1, 9),
 ("prod(X,3,3)", lambda x: x, 3, 3), ("prod(X,5,1)", lambda x: x, 5, 1), ("prod(X,-2,2)", lambda x: x, -2, 2),
 ("prod(X^2+1,1,4)", lambda x: x * x + 1, 1, 4), ("prod(1/X,1,3)", lambda x: 1 / x, 1, 3), ("prod(1-1/X^2,2,10)", lambda x: 1 - 1 / (x * x), 2, 10),
 ("prod(X,-3,-1)", lambda x: x, -3, -1), ("prod(0.5,1,10)", lambda x: Fraction(1, 2) + 0 * x, 1, 10), ("prod(X,1,69)", lambda x: x, 1, 69),
 ("prod(2X-1,1,8)", lambda x: 2 * x - 1, 1, 8), ("prod(X+1/2,1,4)", lambda x: x + Fraction(1, 2), 1, 4),
 ("prod(X,99999,100000)", lambda x: x, 99999, 100000),]
for e, f, a, b in cases: L.append(f"{e} => {disp(P(f, a, b))}")
# nesting and use inside expressions
L.append(f"2*prod(X,1,4)+1 => {disp(2*24+1)}")
L.append(f"prod(X,1,sum(X,1,2)) => {disp(math.factorial(3))}")
L.append(f"prod(X,1,3)*prod(X,1,3) => {disp(36)}")
L.append(f"sum(prod(1,1,3)*X,1,4) => {disp(10)}")
L.append(f"prod(X,1,3)^2 => {disp(36)}")
# limits and errors
L += ["prod(X,1,100) => Math ERROR", "prod(X,1,100000) => Math ERROR", "prod(X,1,100001) => Math ERROR", "prod(X,1,100002) => Time Out",
      "prod(X,1.5,3) => Argument ERROR", "prod(X,1,3.5) => Argument ERROR", "prod(X,1) => Argument ERROR", "prod(X,1,2,3) => Argument ERROR",
      "prod(1/(X-3),1,5) => Math ERROR", "prod(X,1,3 => 6"]
open("tests/cases/product.txt", "w").write("\n".join(L) + "\n")
