#!/usr/bin/env python3
"""Generates tests/cases/stats.txt from independent mpmath computations (Norm 1 display, decimal mode)."""
import sys
from decimal import Decimal, ROUND_HALF_UP
from mpmath import mp, mpf, sqrt, log, exp, matrix, lu_solve

mp.dps = 60


def disp(v):
    d = Decimal(mp.nstr(v, 45))
    if d == 0:
        return "0"
    ex = d.adjusted()
    q = d.scaleb(-ex).quantize(Decimal("1.000000000"), rounding=ROUND_HALF_UP)
    if abs(q) >= 10:
        q = q / 10
        ex += 1
    digits = format(q.normalize(), "f")
    if ex < -2 or ex > 9:
        return digits + "E" + str(ex)
    return format(Decimal(digits).scaleb(ex).normalize(), "f")


out = ["# Generated by tests/tools/make_stat_cases.py (mpmath). Do not edit by hand.", ":reset", ":decimal"]


def median(v):
    v = sorted(v)
    n = len(v)
    return mpf(v[n // 2]) if n % 2 else (mpf(v[n // 2 - 1]) + mpf(v[n // 2])) / 2


def one_var(rows):
    """rows: (x, freq)"""
    out.append(":stat 1var")
    out.append(":data clear")
    out.append(":data " + ";".join("%s,%d" % (x, f) for x, f in rows))
    exp_ = [mpf(x) for x, f in rows for _ in range(f)]
    n = len(exp_)
    s = sum(exp_)
    s2 = sum(v * v for v in exp_)
    m = s / n
    ssq = sum((v - m) ** 2 for v in exp_)
    srt = sorted(exp_)
    h = n // 2
    items = [("n", n), ("sumx", s), ("sumx2", s2), ("xbar", m), ("sigx", sqrt(ssq / n)), ("sx", sqrt(ssq / (n - 1))),
             ("minx", srt[0]), ("maxx", srt[-1]), ("med", median(srt)), ("q1", median(srt[:h])),
             ("q3", median(srt[h + (n % 2):]))]
    for name, v in items:
        out.append("%s => %s" % (name, disp(mpf(v))))


one_var([(2, 1), (4, 3), (5, 2), (7, 1), (9, 1)])
one_var([(10, 1), (20, 1), (30, 1), (40, 1), (50, 1)])
one_var([(1.5, 2), (2.5, 3), (3.5, 5), (4.5, 4), (5.5, 1)])
one_var([(100, 1), (101, 1), (103, 1), (104, 2), (110, 1), (111, 1), (115, 1)])
one_var([(1234567.5, 1), (1234568.5, 1), (1234569.5, 2)])   # offset data: two-pass variance


def lin_fit(xs, ys):
    n = len(xs)
    mx, my = sum(xs) / n, sum(ys) / n
    sxx = sum((x - mx) ** 2 for x in xs)
    syy = sum((y - my) ** 2 for y in ys)
    sxy = sum((x - mx) * (y - my) for x, y in zip(xs, ys))
    b = sxy / sxx
    return my - b * mx, b, sxy / sqrt(sxx * syy)


def two_var(kind, pts, probe_x, probe_y):
    out.append(":stat " + kind)
    out.append(":data clear")
    out.append(":data " + ";".join("%s,%s" % p for p in pts))
    xs = [mpf(str(p[0])) for p in pts]
    ys = [mpf(str(p[1])) for p in pts]
    items = []
    if kind == "lin":
        a, b, r = lin_fit(xs, ys)
        items = [("reg_a", a), ("reg_b", b), ("reg_r", r), ("yhat(%s)" % probe_x, a + b * mpf(probe_x)), ("xhat(%s)" % probe_y, (mpf(probe_y) - a) / b)]
    elif kind == "log":
        a, b, r = lin_fit([log(x) for x in xs], ys)
        items = [("reg_a", a), ("reg_b", b), ("reg_r", r), ("yhat(%s)" % probe_x, a + b * log(mpf(probe_x))), ("xhat(%s)" % probe_y, exp((mpf(probe_y) - a) / b))]
    elif kind == "exp":
        A, b, r = lin_fit(xs, [log(y) for y in ys])
        a = exp(A)
        items = [("reg_a", a), ("reg_b", b), ("reg_r", r), ("yhat(%s)" % probe_x, a * exp(b * mpf(probe_x))), ("xhat(%s)" % probe_y, log(mpf(probe_y) / a) / b)]
    elif kind == "ab":
        A, B, r = lin_fit(xs, [log(y) for y in ys])
        a, b = exp(A), exp(B)
        items = [("reg_a", a), ("reg_b", b), ("reg_r", r), ("yhat(%s)" % probe_x, a * b ** mpf(probe_x))]
    elif kind == "pow":
        A, b, r = lin_fit([log(x) for x in xs], [log(y) for y in ys])
        a = exp(A)
        items = [("reg_a", a), ("reg_b", b), ("reg_r", r), ("yhat(%s)" % probe_x, a * mpf(probe_x) ** b)]
    elif kind == "inv":
        a, b, r = lin_fit([1 / x for x in xs], ys)
        items = [("reg_a", a), ("reg_b", b), ("reg_r", r), ("yhat(%s)" % probe_x, a + b / mpf(probe_x))]
    elif kind == "quad":
        n = len(xs)
        S = lambda k: sum(x ** k for x in xs)
        A = matrix([[n, S(1), S(2)], [S(1), S(2), S(3)], [S(2), S(3), S(4)]])
        rhs = matrix([sum(ys), sum(x * y for x, y in zip(xs, ys)), sum(x * x * y for x, y in zip(xs, ys))])
        c0, c1, c2 = lu_solve(A, rhs)
        items = [("reg_a", c0), ("reg_b", c1), ("reg_c", c2), ("yhat(%s)" % probe_x, c0 + c1 * mpf(probe_x) + c2 * mpf(probe_x) ** 2)]
    out.extend("%s => %s" % (nm, disp(v)) for nm, v in items)
    out.append("xbar => " + disp(sum(xs) / len(xs)))
    out.append("sumxy => " + disp(sum(x * y for x, y in zip(xs, ys))))


two_var("lin", [(1, 2), (2, 4), (3, 5), (4, 4), (5, 5)], 6, 5)
two_var("lin", [(10, 8.04), (8, 6.95), (13, 7.58), (9, 8.81), (11, 8.33), (14, 9.96), (6, 7.24), (4, 4.26), (12, 10.84), (7, 4.82), (5, 5.68)], 15, 7)
two_var("lin", [(0, 32), (10, 50), (20, 68), (30, 86), (100, 212)], 37, 100)
two_var("quad", [(1, 1), (2, 4), (3, 9), (4, 16), (5, 25.5)], 6, 0)
two_var("quad", [(-2, 7.1), (-1, 2.9), (0, 1.2), (1, 3.1), (2, 6.8), (3, 13.2)], 4, 0)
two_var("log", [(1, 0.5), (2, 2.1), (4, 3.4), (8, 5.2), (16, 6.9)], 10, 4)
two_var("exp", [(0, 1.1), (1, 2.9), (2, 7.8), (3, 20.5), (4, 54.9)], 5, 100)
two_var("ab", [(0, 2.0), (1, 3.1), (2, 4.4), (3, 6.8), (4, 10.1)], 5, 0)
two_var("pow", [(1, 2.1), (2, 5.8), (3, 10.9), (4, 16.2), (5, 22.5)], 6, 0)
two_var("inv", [(1, 10.2), (2, 6.1), (3, 4.9), (4, 4.0), (5, 3.8)], 6, 0)
open(sys.argv[1] if len(sys.argv) > 1 else "tests/cases/stats.txt", "w").write("\n".join(out) + "\n")
