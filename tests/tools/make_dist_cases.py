#!/usr/bin/env python3
"""tests/cases/distribution.txt: standard normal P(t), Q(t), R(t) from mpmath."""
import sys
from decimal import Decimal, ROUND_HALF_UP
from mpmath import mp, mpf, erfc, erf, sqrt

mp.dps = 60


def disp(v):
    d = Decimal(mp.nstr(v, 45))
    if d == 0:
        return "0"
    ex = d.adjusted()
    q = d.scaleb(-ex).quantize(Decimal("1.000000000"), rounding=ROUND_HALF_UP)
    if abs(q) >= 10:
        q = q / 10
        ex += 1
    digits = format(q.normalize(), "f")
    if ex < -2 or ex > 9:
        return digits + "E" + str(ex)
    return format(Decimal(digits).scaleb(ex).normalize(), "f")


out = ["# Generated by tests/tools/make_dist_cases.py (mpmath). Do not edit by hand.", ":reset", ":decimal"]
for t in ["0.1", "0.25", "0.5", "0.84", "1", "1.28", "1.645", "1.96", "2", "2.33", "2.576", "3", "3.09", "4", "5", "6.5", "8", "12", "-0.5", "-1", "-1.96", "-2.5", "-3.5", "-6"]:
    x = mpf(t)
    cdf = erfc(-x / sqrt(2)) / 2
    tail = erfc(x / sqrt(2)) / 2
    q = erf(x / sqrt(2)) / 2
    out.append("normp(%s) => %s" % (t, disp(cdf)))
    out.append("normr(%s) => %s" % (t, disp(tail)))
    out.append("normq(%s) => %s" % (t, disp(q)))
out.append("normp(0) => 0.5")
open(sys.argv[1] if len(sys.argv) > 1 else "tests/cases/distribution.txt", "w").write("\n".join(out) + "\n")
