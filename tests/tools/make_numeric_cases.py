#!/usr/bin/env python3
"""
Generates tests/cases/calculus.txt: expected values computed independently with mpmath
(60 digits) and formatted the way the calculator displays them (Norm 1, 10 digits).
"""
import sys
from decimal import Decimal, ROUND_HALF_UP
from mpmath import mp, mpf, sin, cos, tan, exp, log, sqrt, atan, pi, diff, quad, findroot, sinh, cosh, asin, e

mp.dps = 60


def disp(v):
    d = Decimal(mp.nstr(v, 40))
    if d == 0:
        return "0"
    ex = d.adjusted()
    q = d.scaleb(-ex).quantize(Decimal("1.000000000"), rounding=ROUND_HALF_UP)
    if q.copy_abs() >= 10:
        q = q / 10
        ex += 1
    digits = format(q.normalize(), "f")
    if ex < -2 or ex > 9:
        return digits + "E" + str(ex)
    return format(Decimal(digits).scaleb(ex).normalize(), "f")


rad = lambda f: (lambda x: f(x))
CASES = []   # (mode, expr, value)
D = lambda s, f, x0: ("rad", "ddx(%s,%s)" % (s, x0), diff(f, mpf(x0) if not isinstance(x0, str) else eval(x0)))
CASES += [
    ("rad", "ddx(X^3,0)", mpf(0)),
    ("deg", "ddx(X^3,2)", diff(lambda x: x ** 3, 2)),
    ("deg", "ddx(X^2,3)", diff(lambda x: x ** 2, 3)),
    ("deg", "ddx(5X^4-3X^2+X,2)", diff(lambda x: 5 * x ** 4 - 3 * x ** 2 + x, 2)),
    ("rad", "ddx(sin(X),1)", diff(sin, 1)),
    ("rad", "ddx(cos(X),2)", diff(cos, 2)),
    ("rad", "ddx(ln(X),2)", diff(log, 2)),
    ("rad", "ddx(e^X,1)", diff(exp, 1)),
    ("rad", "ddx(e^(2X),0.5)", diff(lambda x: exp(2 * x), mpf("0.5"))),
    ("rad", "ddx(X^X,2)", diff(lambda x: x ** x, 2)),
    ("rad", "ddx(sqrt(X),4)", diff(sqrt, 4)),
    ("rad", "ddx(tan(X),0.5)", diff(tan, mpf("0.5"))),
    ("rad", "ddx(atan(X),1)", diff(atan, 1)),
    ("rad", "ddx(1/X,2)", diff(lambda x: 1 / x, 2)),
    ("rad", "ddx(X*sin(X),3)", diff(lambda x: x * sin(x), 3)),
    ("rad", "ddx(ln(X^2+1),1.5)", diff(lambda x: log(x ** 2 + 1), mpf("1.5"))),
    ("rad", "ddx(sinh(X),1)", diff(sinh, 1)),
    ("rad", "ddx(X^3,-2)", diff(lambda x: x ** 3, -2)),
    ("rad", "ddx(sin(X),0)", diff(sin, 0)),
    ("rad", "ddx(e^X,10)", diff(exp, 10)),
    ("rad", "ddx(X^2,1000)", diff(lambda x: x ** 2, 1000)),
]


def I(expr, f, a, b, mode="rad"):
    CASES.append((mode, "integral(%s,%s,%s)" % (expr, a, b), quad(f, [mpf(eval(str(a), {"pi": pi, "e": e})), mpf(eval(str(b), {"pi": pi, "e": e}))])))


I("X^2", lambda x: x ** 2, 0, 3)
I("X^3-2X+1", lambda x: x ** 3 - 2 * x + 1, -1, 2)
I("sin(X)", sin, 0, "pi")
I("cos(X)", cos, 0, 1)
I("1/X", lambda x: 1 / x, 1, 2)
I("e^X", exp, 0, 1)
I("e^(-X^2)", lambda x: exp(-x ** 2), 0, 1)
I("e^(-X^2)", lambda x: exp(-x ** 2), -2, 2)
I("sqrt(X)", sqrt, 0, 4)
I("1/sqrt(X)", lambda x: 1 / sqrt(x), 0, 1)
I("ln(X)", log, 1, 10)
I("ln(X)", log, 0, 1)
I("1/(1+X^2)", lambda x: 1 / (1 + x ** 2), 0, 1)
I("X*e^X", lambda x: x * exp(x), 0, 2)
I("sin(X)^2", lambda x: sin(x) ** 2, 0, "pi")
I("sqrt(1-X^2)", lambda x: sqrt(1 - x ** 2), 0, 1)
I("1/sqrt(1-X^2)", lambda x: 1 / sqrt(1 - x ** 2), 0, 0.5)
I("X^2*sin(X)", lambda x: x ** 2 * sin(x), 0, 3)
I("tan(X)", tan, 0, 1)
CASES.append(("rad", "integral(abs(X),-2,3)", mpf("6.5")))
I("X^10", lambda x: x ** 10, 0, 2)
I("e^X*sin(X)", lambda x: exp(x) * sin(x), 0, 3)
I("1/X", lambda x: 1 / x, 2, 1)
I("sin(100X)", lambda x: sin(100 * x), 0, 1)


def S(eq, f, guess, mode="rad", mpg=None):
    CASES.append((mode, "solve(%s,%s)" % (eq, guess), findroot(f, mpf(guess if mpg is None else mpg), tol=1e-50, maxsteps=200)))


S("X^2=2", lambda x: x ** 2 - 2, 1)
S("X^2=2", lambda x: x ** 2 - 2, -1)
S("X^3-2X-5=0", lambda x: x ** 3 - 2 * x - 5, 2)
S("cos(X)=X", lambda x: cos(x) - x, 1)
S("e^X=5", lambda x: exp(x) - 5, 1)
S("ln(X)=2", lambda x: log(x) - 2, 1)
S("X*e^X=1", lambda x: x * exp(x) - 1, 0)
S("sin(X)=X/2", lambda x: sin(x) - x / 2, 2)
S("X^4-3X^2+1=0", lambda x: x ** 4 - 3 * x ** 2 + 1, 1)
S("X^4-3X^2+1=0", lambda x: x ** 4 - 3 * x ** 2 + 1, 0.5)
S("2^X=X^2", lambda x: 2 ** x - x ** 2, 3.5, mpg=4)
S("2^X=X^2", lambda x: 2 ** x - x ** 2, -1)
S("sqrt(X)=X-2", lambda x: sqrt(x) - x + 2, 5)
S("3X+7=2X-4", lambda x: 3 * x + 7 - 2 * x + 4, 0)
S("X^3=1000000", lambda x: x ** 3 - 1000000, 1, mpg=90)
S("1/X=3", lambda x: 1 / x - 3, 1, mpg=0.3)
S("X^2-4X+4=0", lambda x: x ** 2 - 4 * x + 4, 1)  # replaced below (double root has no sign change)
CASES.pop()
S("tanh(X)=0.5", lambda x: mp.tanh(x) - mpf("0.5"), 0)
S("X^5+X=1", lambda x: x ** 5 + x - 1, 0)
S("e^(-X)=X", lambda x: exp(-x) - x, 0)
S("sin(X)=0.5", lambda x: sin(x) - mpf("0.5"), 0.4)

out = ["# Generated by tests/tools/make_numeric_cases.py (mpmath, 60 digits). Do not edit by hand.", ":reset"]
mode = None
for m, expr, v in CASES:
    if m != mode:
        out.append(":" + m)
        mode = m
    out.append("%s => %s" % (expr, disp(v)))
open(sys.argv[1] if len(sys.argv) > 1 else "tests/cases/calculus.txt", "w").write("\n".join(out) + "\n")
print(len(CASES), "cases")
