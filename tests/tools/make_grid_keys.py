#!/usr/bin/env python3
"""Generates tests/ui/grid.txt: key sequences that enter linear systems through the coefficient grid (MENU > Equations >
Linear system), including corrections, and the expected pages computed with exact Python Fractions."""
import random, sys
sys.path.insert(0, "tests/tools")
from make_simul_cases import solve, mixed          # noqa: E402  (re-runs the case generator; harmless)
from fractions import Fraction as F

def key(v):
    s = ("NEG " if v < 0 else "") + " ".join(str(abs(int(v))))
    return s

def grid_keys(n, rows):
    pick = {2: 7, 3: 8, 4: 9}[n]
    k = "MENU " + "DOWN " * 9 + "EXE " + str(pick) + " "
    return k, " ".join(key(v) + " EXE" for r in rows for v in r)

L = ["# Generated by tests/tools/make_grid_keys.py (exact Fractions). Do not edit by hand."]
rnd = random.Random(77)
for t in range(24):
    n = [2, 3, 4][t % 3]
    rows = [[rnd.randint(-9, 9) for _ in range(n + 1)] for _ in range(n)]
    kind, sol = solve(rows)
    head, body = grid_keys(n, rows)
    if kind == "unique":
        for i in range(n):
            L.append(f"{head}{body} EXE" + " DOWN" * i + f" => {mixed(sol[i])}")
    else:
        L.append(f"{head}{body} EXE => " + ("No Solution" if kind == "inconsistent" else "Infinite Solutions"))
# --- corrections and editing keys ---------------------------------------------------------------
rows = [[1, 1, 1, 1, 10], [1, -1, 1, -1, -2], [2, 1, -1, 1, 3], [1, 2, 3, 4, 30]]
kind, sol = solve(rows)
head, body = grid_keys(4, rows)
cells = [key(v) + " EXE" for r in rows for v in r]
def seq(c): return head + " ".join(c)
# A: first cell entered wrongly as 7; go back to it (UP x3, LEFT x4), retype, solve (EXE when not editing)
wrong = list(cells); wrong[0] = "7 EXE"
for i in range(4):
    L.append(seq(wrong) + " UP UP UP LEFT LEFT LEFT LEFT 1 EXE EXE" + " DOWN" * i + f" => {mixed(sol[i])}")
# B: DEL removes the last typed character before the value is accepted
back = list(cells); back[0] = "1 2 DEL EXE"; back[5] = "1 9 DEL DEL 1 EXE"
L.append(seq(back) + f" EXE => {mixed(sol[0])}")
# C: AC cancels the entry in progress (the cell keeps its old value); then the right value is typed
canc = list(cells[:-1]) + ["9 AC", cells[-1], "EXE"]
L.append(seq(canc) + f" => {mixed(sol[0])}")
# D: DEL on a cell that is not being edited sets it to 0
rows0 = [[0, 1, 0, 0, 2], [1, 0, 0, 0, 1], [0, 0, 1, 0, 3], [0, 0, 0, 1, 4]]
k0, sol0 = solve(rows0)
c0 = [key(v) + " EXE" for r in rows0 for v in r]
c0[0] = "5 EXE LEFT DEL RIGHT"
L.append(seq(c0) + f" EXE => {mixed(sol0[0])}")
# E: result paging with UP after DOWN, and the equations-grid reopens with the values kept
L.append(seq(cells) + f" EXE DOWN DOWN UP => {mixed(sol[1])}")
# F: leaving with AC keeps the values: reopen and solve straight away
L.append(seq(cells) + " AC " + head + f"EXE => {mixed(sol[0])}")
# G: 2- and 3-unknown grids on the same keys
for n, rws in [(2, [[1, 1, 3], [1, -1, 1]]), (3, [[1, 1, 1, 6], [0, 2, 5, -4], [3, -1, 1, -1]])]:
    kk, ss = solve(rws); hh, bb = grid_keys(n, rws)
    for i in range(n): L.append(f"{hh}{bb} EXE" + " DOWN" * i + f" => {mixed(ss[i])}")
# H: wrong-size reuse: opening another grid size starts clean (zeros) -> singular
L.append(grid_keys(3, rows)[0] + "EXE => Infinite Solutions")
open("tests/ui/grid.txt", "w").write("\n".join(L) + "\n")
print(len(L), "lines")
